#!/usr/bin/env python3
"""Embed shared rule data in Dart; --check catches stale mobile copies in CI."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
rules = json.loads((ROOT / 'data/playbook_rules.json').read_text())
payload = json.dumps(rules, ensure_ascii=False, separators=(',', ':'))
assert "'''" not in payload
output = "// Generated by scripts/generate_playbook.py; edit data/playbook_rules.json.\n"
output += "import 'dart:convert';\n\n"
output += "// dart format off\n"
output += "final Map<String, dynamic> playbookRules =\n"
output += "    jsonDecode(r'''" + payload + "''') as Map<String, dynamic>;\n"
output += "// dart format on\n"
target = ROOT / 'mobile/lib/playbook_rules.g.dart'
if args.check:
    if not target.exists() or target.read_text() != output:
        raise SystemExit('Run python3 scripts/generate_playbook.py to update Dart rules.')
    print('Shared playbook rules match the mobile copy.')
else:
    target.write_text(output)
